#!/usr/bin/env bash
# Tests for scripts/init-landing-zone.sh: run it non-interactively into a temp
# dir and assert the output is yamllint-clean (same rules as pre-commit) and
# carries the substituted values. Also covers the refusal paths.
#
#   bash scripts/tests/test-init-landing-zone.sh      (make test-scripts; CI: meta-lint)
#
# yamllint resolution: $YAMLLINT, else `yamllint` on PATH, else
# `uvx --from yamllint==1.37.1 yamllint`. Missing yamllint is a failure.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
SCRIPT="${REPO_ROOT}/scripts/init-landing-zone.sh"
# Same rules as the pre-commit yamllint hook (.pre-commit-config.yaml).
YAMLLINT_RULES='{extends: default, rules: {line-length: {max: 120}, document-start: disable}}'

workdir="$(mktemp -d)"
trap 'rm -rf "${workdir}"' EXIT

passes=0
failures=0
pass() { passes=$((passes + 1)); printf '  ok   %s\n' "$1"; }
fail() { failures=$((failures + 1)); printf '  FAIL %s\n' "$1" >&2; }

yamllint_cmd() {
  if [[ -n "${YAMLLINT:-}" ]]; then
    # shellcheck disable=SC2086 # YAMLLINT may be a multi-word command.
    ${YAMLLINT} "$@"
  elif command -v yamllint >/dev/null 2>&1; then
    yamllint "$@"
  elif command -v uvx >/dev/null 2>&1; then
    uvx --quiet --from yamllint==1.37.1 yamllint "$@"
  else
    echo "yamllint not found (install it, or set YAMLLINT / install uv)" >&2
    return 127
  fi
}

# assert_line FILE REGEX DESCRIPTION — FILE has a line matching the ERE.
assert_line() {
  if grep -qE -- "$2" "$1"; then pass "$3"; else fail "$3 (no line matching /$2/)"; fi
}
assert_no_line() {
  if grep -qE -- "$2" "$1"; then fail "$3 (unexpected line matching /$2/)"; else pass "$3"; fi
}
# section_value FILE SECTION KEY — value of "  KEY:" inside top-level "SECTION:".
section_value() {
  awk -v s="$2" -v k="$3" '
    /^[a-z_]+:/ { cur = $1; sub(":", "", cur) }
    cur == s && $0 ~ "^  " k ": " { sub("^  " k ": ", ""); print; exit }
  ' "$1"
}
assert_eq() {
  if [[ "$1" == "$2" ]]; then pass "$3"; else fail "$3 (got '$1', want '$2')"; fi
}

