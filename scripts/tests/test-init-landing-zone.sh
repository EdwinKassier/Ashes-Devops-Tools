  assert_line "${out}" '^    organization: acme-tfc$' "org.tfc.organization"
  assert_eq "$(section_value "${out}" gcp enabled)" "true" "gcp.enabled"
  assert_eq "$(section_value "${out}" aws enabled)" "true" "aws.enabled"
  assert_eq "$(section_value "${out}" saas enabled)" "false" "saas.enabled"
  assert_eq "$(section_value "${out}" gcp billing_account)" '"0A1B2C-3D4E5F-6A7B8C"' "gcp.billing_account"
  assert_eq "$(section_value "${out}" gcp admin_email)" "admin@acme.com" "gcp.admin_email"
  assert_eq "$(section_value "${out}" aws management_account_id)" '"123456789012"' "aws.management_account_id"
  assert_line "${out}" 'arn:aws:iam::123456789012:role/tfc-mgmt-apply' "AWS run-role ARN uses the management account"
  assert_line "${out}" '^  log_archive_bucket_name: acme-org-log-archive$' "log-archive bucket uses the prefix"
  assert_line "${out}" 'GCP organization ID 123456789' "--gcp-org-id written as a comment"
  assert_line "${out}" 'us-central1' "GCP region substituted"
  assert_line "${out}" 'us-east-1' "AWS region substituted"
