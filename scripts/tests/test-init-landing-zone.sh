#!/usr/bin/env bash
# Tests for scripts/init-landing-zone.sh: run it non-interactively into a temp
# dir and assert the output is yamllint-clean (same rules as pre-commit) and
# carries the substituted values. Also covers the refusal paths.
#
#   bash scripts/tests/test-init-landing-zone.sh      (make test-scripts; CI: meta-lint)
#
# yamllint resolution: $YAMLLINT, else `yamllint` on PATH, else
# `uvx --from yamllint==1.37.1 yamllint`. Missing yamllint is a failure.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
SCRIPT="${REPO_ROOT}/scripts/init-landing-zone.sh"
# Same rules as the pre-commit yamllint hook (.pre-commit-config.yaml).
YAMLLINT_RULES='{extends: default, rules: {line-length: {max: 120}, document-start: disable}}'

workdir="$(mktemp -d)"
trap 'rm -rf "${workdir}"' EXIT

passes=0
failures=0
pass() { passes=$((passes + 1)); printf '  ok   %s\n' "$1"; }
fail() { failures=$((failures + 1)); printf '  FAIL %s\n' "$1" >&2; }

yamllint_cmd() {
  if [[ -n "${YAMLLINT:-}" ]]; then
    # shellcheck disable=SC2086 # YAMLLINT may be a multi-word command.
    ${YAMLLINT} "$@"
  elif command -v yamllint >/dev/null 2>&1; then
    yamllint "$@"
  elif command -v uvx >/dev/null 2>&1; then
    uvx --quiet --from yamllint==1.37.1 yamllint "$@"
  else
    echo "yamllint not found (install it, or set YAMLLINT / install uv)" >&2
    return 127
  fi
}

# assert_line FILE REGEX DESCRIPTION — FILE has a line matching the ERE.
assert_line() {
  if grep -qE -- "$2" "$1"; then pass "$3"; else fail "$3 (no line matching /$2/)"; fi
}
assert_no_line() {
  if grep -qE -- "$2" "$1"; then fail "$3 (unexpected line matching /$2/)"; else pass "$3"; fi
}
# section_value FILE SECTION KEY — value of "  KEY:" inside top-level "SECTION:".
section_value() {
  awk -v s="$2" -v k="$3" '
    /^[a-z_]+:/ { cur = $1; sub(":", "", cur) }
    cur == s && $0 ~ "^  " k ": " { sub("^  " k ": ", ""); print; exit }
  ' "$1"
}
assert_eq() {
  if [[ "$1" == "$2" ]]; then pass "$3"; else fail "$3 (got '$1', want '$2')"; fi
}

echo "==> happy path: gcp + aws, every value supplied"
out="${workdir}/landing-zone.yaml"
log="${workdir}/run.log"
if bash "${SCRIPT}" --non-interactive --output "${out}" \
  --org-name acme --display-name "Acme Corp" --tfc-org acme-tfc --clouds gcp,aws \
  --domain acme.com --billing-account 0A1B2C-3D4E5F-6A7B8C \
  --gcp-admin-email admin@acme.com --aws-management-account 123456789012 \
  --gcp-org-id 123456789 --gcp-region us-central1 --aws-region us-east-1 \
  </dev/null >"${log}" 2>&1; then
  pass "script exits 0"
else
  fail "script exits 0"; cat "${log}" >&2
fi

if [[ -s "${out}" ]]; then
  pass "output file written"
  if yamllint_cmd -s -d "${YAMLLINT_RULES}" "${out}"; then pass "output is yamllint-clean"; else fail "output is yamllint-clean"; fi

  assert_eq "$(section_value "${out}" org name)" "acme" "org.name"
  assert_eq "$(section_value "${out}" org prefix)" "acme" "org.prefix defaults to --org-name"
  assert_eq "$(section_value "${out}" org domain)" "acme.com" "org.domain"
  assert_eq "$(section_value "${out}" org display_name)" '"Acme Corp"' "org.display_name (quoted)"
  assert_line "${out}" '^    organization: acme-tfc$' "org.tfc.organization"
  assert_eq "$(section_value "${out}" gcp enabled)" "true" "gcp.enabled"
  assert_eq "$(section_value "${out}" aws enabled)" "true" "aws.enabled"
  assert_eq "$(section_value "${out}" saas enabled)" "false" "saas.enabled"
  assert_eq "$(section_value "${out}" gcp billing_account)" '"0A1B2C-3D4E5F-6A7B8C"' "gcp.billing_account"
  assert_eq "$(section_value "${out}" gcp admin_email)" "admin@acme.com" "gcp.admin_email"
  assert_eq "$(section_value "${out}" aws management_account_id)" '"123456789012"' "aws.management_account_id"
  assert_line "${out}" 'arn:aws:iam::123456789012:role/tfc-mgmt-apply' "AWS run-role ARN uses the management account"
  assert_line "${out}" '^  log_archive_bucket_name: acme-org-log-archive$' "log-archive bucket uses the prefix"
  assert_line "${out}" 'GCP organization ID 123456789' "--gcp-org-id written as a comment"
  assert_line "${out}" 'us-central1' "GCP region substituted"
  assert_line "${out}" 'us-east-1' "AWS region substituted"
  assert_no_line "${out}" 'europe-west2|eu-west-2' "no default regions left"
  assert_no_line "${out}" '^[^#]*(my-org|REPLACE_WITH_12_DIGIT_ID|REPLACE_WITH_BILLING_ACCOUNT_ID|REPLACE_WITH_ADMIN_EMAIL)' \
    "no upstream placeholders left in values"
  assert_line "${out}" '^# Generated by scripts/init-landing-zone.sh' "generated-file header"
  assert_line "${out}" '^        platform:$' "gcp scaffold declares a platform service team"
  assert_line "${out}" '^          service_team: platform$' "gcp scaffold points the example service at the platform team"
  assert_line "${out}" 'subnet_name: acme-dev-vpc-private-us-central1-b' "platform team subnet uses the prefix and region"
  assert_no_line "${out}" '^          github: ' "gcp scaffold example service has no placeholder deploy identity"

  if command -v python3 >/dev/null 2>&1 && python3 -c 'import yaml' 2>/dev/null; then
    if python3 - "${out}" <<'PY'
import sys, yaml
doc = yaml.safe_load(open(sys.argv[1]))
assert doc["org"]["name"] == "acme"
assert doc["org"]["tfc"]["organization"] == "acme-tfc"
assert doc["gcp"]["enabled"] is True and doc["aws"]["enabled"] is True and doc["saas"]["enabled"] is False
assert doc["aws"]["management_account_id"] == "123456789012"
assert doc["org"]["regions"]["gcp"] == "us-central1" and doc["org"]["regions"]["aws"] == "us-east-1"
PY
    then pass "parsed YAML has the expected types and values"; else fail "parsed YAML has the expected types and values"; fi
  fi
else
  fail "output file written"
fi

echo "==> refusal paths"
expect_reject() {
  local desc="$1"; shift
  if bash "${SCRIPT}" --non-interactive "$@" </dev/null >"${log}" 2>&1; then
    fail "${desc} (exited 0)"
  else
    pass "${desc}"
  fi
}
expect_reject "refuses to overwrite without --force" --output "${out}" --org-name acme --clouds aws
expect_reject "rejects an invalid --org-name" --output "${workdir}/a.yaml" --org-name Acme --clouds aws
expect_reject "rejects the upstream placeholder org name" --output "${workdir}/b.yaml" --org-name my-org --clouds aws
expect_reject "requires --domain when gcp is enabled" --output "${workdir}/c.yaml" --org-name acme --clouds gcp
expect_reject "rejects an unknown cloud" --output "${workdir}/d.yaml" --org-name acme --clouds azure
expect_reject "rejects a malformed AWS account ID" --output "${workdir}/e.yaml" --org-name acme --clouds aws \
  --aws-management-account 1234
if [[ -e "${workdir}/a.yaml" ]]; then fail "a rejected run writes no file"; else pass "a rejected run writes no file"; fi

echo "==> --force overwrites; saas-only leaves gcp/aws disabled"
if bash "${SCRIPT}" --non-interactive --force --output "${out}" --org-name beta --clouds saas </dev/null >"${log}" 2>&1; then
  pass "--force overwrites an existing file"
  assert_eq "$(section_value "${out}" org name)" "beta" "overwritten org.name"
  assert_eq "$(section_value "${out}" gcp enabled)" "false" "saas-only: gcp.enabled false"
  assert_eq "$(section_value "${out}" aws enabled)" "false" "saas-only: aws.enabled false"
  assert_eq "$(section_value "${out}" saas enabled)" "true" "saas-only: saas.enabled true"
  if yamllint_cmd -s -d "${YAMLLINT_RULES}" "${out}"; then pass "saas-only output is yamllint-clean"; else fail "saas-only output is yamllint-clean"; fi
else
  fail "--force overwrites an existing file"; cat "${log}" >&2
fi

echo "==> AWS email pattern, GitHub owner and SaaS stack flags"
out2="${workdir}/flags.yaml"
if bash "${SCRIPT}" --non-interactive --output "${out2}" --org-name acme --tfc-org acme-tfc --clouds aws,saas \
  --aws-management-account 123456789012 --aws-email-pattern 'aws+{key}@acme.io' --github-owner acme \
  --supabase-org abcdefgh1234 --vercel-team team_x --github-repo acme/web </dev/null >"${log}" 2>&1; then
  pass "flags run exits 0"
  assert_line "${out2}" 'log_archive: \{email: aws\+log-archive@acme\.io' "email pattern fills the account emails"
  assert_no_line "${out2}" '^[^#]*@example\.com' "no example.com emails left"
  assert_line "${out2}" '^  github_federation_owners:$' "github_federation_owners uncommented"
  assert_line "${out2}" '^    - acme$' "github owner listed"
  assert_line "${out2}" '^      organization_id: abcdefgh1234$' "saas.defaults.supabase.organization_id"
  assert_line "${out2}" '^      team_id: team_x$' "saas.defaults.vercel.team_id"
  assert_line "${out2}" '^        github_repo: acme/web$' "saas.stacks.web.vercel.github_repo"
  assert_line "${out2}" '^        project_name: acme-web$' "SaaS project names default to <prefix>-web"
  assert_no_line "${log}" 'Still placeholders' "no placeholders reported for the enabled clouds"
  if yamllint_cmd -s -d "${YAMLLINT_RULES}" "${out2}"; then pass "flags output is yamllint-clean"; else fail "flags output is yamllint-clean"; fi
else
  fail "flags run exits 0"; cat "${log}" >&2
fi
expect_reject "rejects an email pattern without {key}" --output "${workdir}/f.yaml" --org-name acme --clouds aws \
  --aws-email-pattern 'aws@acme.io'
expect_reject "rejects an example.com email pattern" --output "${workdir}/g.yaml" --org-name acme --clouds aws \
  --aws-email-pattern 'aws+{key}@example.com'

echo "==> a gcp-only run does not report AWS placeholders"
out3="${workdir}/gcp-only.yaml"
if bash "${SCRIPT}" --non-interactive --output "${out3}" --org-name acme --tfc-org acme-tfc --clouds gcp --domain acme.com \
  </dev/null >"${log}" 2>&1; then
  assert_no_line "${log}" 'example\.com, ou:' "AWS account emails not reported on a gcp-only run"
else
  fail "gcp-only run exits 0"; cat "${log}" >&2
fi

echo
echo "test-init-landing-zone: ${passes} passed, ${failures} failed"
[[ "${failures}" -eq 0 ]]
