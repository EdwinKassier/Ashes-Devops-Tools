  assert_no_line "${out}" '^          github: ' "gcp scaffold example service has no placeholder deploy identity"
  assert_eq "$(section_value "${out}" aws enable_org_config_recorders)" "false" "first pass: org Config recorders off"
  assert_eq "$(section_value "${out}" aws enable_config_recorder_scp)" "false" "first pass: recorder SCP off"

  if command -v python3 >/dev/null 2>&1 && python3 -c 'import yaml' 2>/dev/null; then
    if python3 - "${out}" <<'PY'
import sys, yaml
doc = yaml.safe_load(open(sys.argv[1]))
assert doc["org"]["name"] == "acme"
assert doc["org"]["tfc"]["organization"] == "acme-tfc"
assert doc["gcp"]["enabled"] is True and doc["aws"]["enabled"] is True and doc["saas"]["enabled"] is False
assert doc["aws"]["management_account_id"] == "123456789012"
assert doc["org"]["regions"]["gcp"] == "us-central1" and doc["org"]["regions"]["aws"] == "us-east-1"
PY
    then pass "parsed YAML has the expected types and values"; else fail "parsed YAML has the expected types and values"; fi
  fi
else
  fail "output file written"
fi

echo "==> refusal paths"
expect_reject() {
  local desc="$1"; shift
  if bash "${SCRIPT}" --non-interactive "$@" </dev/null >"${log}" 2>&1; then
    fail "${desc} (exited 0)"
  else
    pass "${desc}"
  fi
}
