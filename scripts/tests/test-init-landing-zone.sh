  pass "output file written"
  if yamllint_cmd -s -d "${YAMLLINT_RULES}" "${out}"; then pass "output is yamllint-clean"; else fail "output is yamllint-clean"; fi

  assert_eq "$(section_value "${out}" org name)" "acme" "org.name"
  assert_eq "$(section_value "${out}" org prefix)" "acme" "org.prefix defaults to --org-name"
  assert_eq "$(section_value "${out}" org domain)" "acme.com" "org.domain"
